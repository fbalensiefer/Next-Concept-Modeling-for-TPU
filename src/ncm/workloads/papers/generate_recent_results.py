"""Generate the current evidence tables from archived raw observations."""
import argparse,hashlib,json,statistics
from pathlib import Path

ROOT=Path(__file__).resolve().parents[4]


def generate():
    facts={'sources':{}};macros=[]
    def read(path):
        p=ROOT/path;facts['sources'][path]=hashlib.sha256(p.read_bytes()).hexdigest();return json.loads(p.read_text())
    validation=read('paper/validation_current.json')
    assert validation['passed']==62 and validation['failed']==0
    macros.append('\\newcommand{\\CurrentTestCases}{'+str(validation['passed'])+'}')
    maintenance=read('reports/maintenance-ablation/results.json')
    domains=read('reports/fresh-domain-validation/results.json')
    priors=read('reports/dependency-validation/results.json')
    alignment=read('reports/alignment-diagnosis/results.json')
    innovations=read('reports/invertible-baselines/results.json')
    assert len(maintenance)==100 and len(domains)==360 and len(priors)==480
    assert len({(r['domain'],r['seed'],r['arm']) for r in priors})==120
    def table(command,caption,label,columns,header,rows):
        macros.append('\\newcommand{\\'+command+'}{%\n'+r'\begin{table}[t]\centering\small'+'\n'+r'\caption{'+caption+'}\n'+r'\label{'+label+'}\n'+r'\begin{tabularx}{\linewidth}{'+columns+'}'+r'\toprule'+'\n'+header+r'\\\midrule'+'\n'+'\n'.join(row+r'\\' for row in rows)+'\n'+r'\bottomrule\end{tabularx}\end{table}}')
    rows=[];facts['maintenance']={}
    for name,label in [('minimal_ema','Minimal EMA'),('ema_recovery','EMA + recovery'),('reference','Reference'),('fixed_binary','Fixed binary')]:
        rr=[r for r in maintenance if r['treatment']==name and (name!='ema_recovery' or r['study']=='maintenance-ablation')]
        m=dict(tv=statistics.mean(r['after']['factorized_oracle_tv'] for r in rr),reconstruction=statistics.mean(r['after']['sequence_reconstruction'] for r in rr),usage_failures=sum(r['collapsed_fraction']>.05 for r in rr));facts['maintenance'][name]=m
        rows.append(f"{label} & {100*m['reconstruction']:.3f} & {m['usage_failures']}/20 & {m['tv']:.4f}")
    table('RecentMaintenanceTable','Matched historical-seed ablations. Reconstruction is sequence accuracy in percent; usage failures exceed 5 percent collapsed minibatches. All objectives and schedules remain shared.','tab:recentmaintenance','@{}Yrrr@{}',r'Condition & Recon. & Usage failures & Oracle TV',rows)
    names=list(dict.fromkeys(r['domain'] for r in domains));labels=['Original source','Biased independent','Markov','Noisy parity','Skewed modes','Alternating modes'];rows=[];facts['domains']={}
    for name,label in zip(names,labels):
        cells=[];facts['domains'][name]={}
        for t in ['ema_recovery','reference','fixed_binary']:
            rr=[r for r in domains if r['domain']==name and r['treatment']==t];assert len(rr)==20
            m=dict(tv=statistics.mean(r['after']['factorized_oracle_tv'] for r in rr),fidelity_failures=sum(bool(r['failures']) for r in rr));facts['domains'][name][t]=m;cells.append(f"{m['tv']:.3f} ({m['fidelity_failures']})")
        rows.append(label+' & '+' & '.join(cells))
    table('RecentDomainTable','Fresh seeds 31--35 across all four objective arms. Cells give mean factorized-oracle output TV and fidelity failures out of 20 models in parentheses. No prior is trained in this study.','tab:recentdomains','@{}Yrrr@{}','Source & EMA + recovery & Reference & Fixed binary',rows)
    rows=[];facts['priors']={}
    for name,label in zip(names,labels):
        eligible=[r for r in priors if r['domain']==name and r['model']=='independent' and r['codec_eligible']];cells=[];facts['priors'][name]={}
        for model in ['independent','conditional_tree','joint_fine']:
            rr=[r for r in priors if r['domain']==name and r['model']==model and r['codec_eligible']];m=statistics.mean(r['output_tv'] for r in rr);facts['priors'][name][model]=m;cells.append(f'{m:.4f}')
        rows.append(label+' & '+str(len(eligible))+' & '+' & '.join(cells))
    table('RecentPriorTable','Training-only prior fits on frozen reference codecs passing the sampled fidelity check. Lower decoded output TV is better. All-codec results, including flagged failures, remain in the public report.','tab:recentpriors','@{}Yrrrr@{}','Source & Eligible & Indep. & Tree & Joint',rows)
    facts['alignment']=alignment['invariants'];facts['innovations']={k:v.get('invertible_innovations') for k,v in innovations.items() if 'invertible_innovations' in v}
    assert facts['alignment']['last_bit_pair_target_max_difference']==0
    assert all(v['bijective'] and v['tv']<1e-14 for v in facts['innovations'].values())
    return '% Generated by generate_recent_results.py; do not edit.\n'+'\n'.join(macros)+'\n',json.dumps(facts,indent=2)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    tex,data=generate()
    for name,content in [('recent_results.tex',tex),('recent_results.json',data)]:
        path=ROOT/'paper/generated'/name
        if args.check:assert path.read_text()==content,path
        else:path.write_text(content)
    print('Recent manuscript evidence matches archived observations.')
